/// Watches the general pasteboard (there is no change notification on macOS, so we poll the
/// cheap `changeCount`). Skips password-manager items marked concealed or transient
/// (nspasteboard.org conventions) and our own writes.
final class ClipboardWatcher {
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var ownCount = -1
    var onCopy: ((String) -> Void)?

    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            self?.poll()
        }
        t.tolerance = 0.25
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Text from the phone: put it on the pasteboard without echoing it back.
    func set(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        ownCount = pb.changeCount
        lastCount = pb.changeCount
    }

    var currentText: String? { NSPasteboard.general.string(forType: .string) }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard pb.changeCount != ownCount else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped) else {
            Log.info("clip.skipped_concealed")
            return
        }
        if let s = pb.string(forType: .string), !s.isEmpty { onCopy?(s) }
    }
}

/// Posts mirrored notifications through UserNotifications. macOS Focus / Do Not Disturb is
/// applied by the system to everything we post; "silent" apps are delivered without sound
/// and as passive (no banner).
final class Notifier: NSObject, UNUserNotificationCenterDelegate {
    static let category = "tether.mirror"
    private let center = UNUserNotificationCenter.current()
    var onDismiss: ((String) -> Void)?
    var onOpen: ((String) -> Void)?

    func setUp() {
        center.delegate = self
        center.setNotificationCategories([
            UNNotificationCategory(identifier: Self.category, actions: [], intentIdentifiers: [], options: [.customDismissAction]),
        ])
    }

    func requestAuthorization(_ done: @escaping (Bool) -> Void) {
        center.requestAuthorization(options: [.alert, .sound, .badge]) { granted, error in
            if let error { Log.warn("notify.auth_error", ["reason": "\(error)"]) }
            done(granted)
        }
    }

    func authorizationStatus(_ done: @escaping (UNAuthorizationStatus) -> Void) {
        center.getNotificationSettings { done($0.authorizationStatus) }
    }

    func post(key: String, threadId: String, title: String, subtitle: String?, body: String, banner: Bool, sound: Bool) {
        let c = UNMutableNotificationContent()
        c.title = title
        if let subtitle { c.subtitle = subtitle }
        c.body = body
        c.threadIdentifier = threadId
        c.categoryIdentifier = Self.category
        c.userInfo = ["key": key]
        if banner && sound { c.sound = .default }
        if #available(macOS 12.0, *) { c.interruptionLevel = banner ? .active : .passive }
        center.add(UNNotificationRequest(identifier: key, content: c, trigger: nil)) { err in
            if let err { Log.warn("notify.post_failed", ["reason": "\(err)"]) }
        }
    }

    func postLocal(id: String, title: String, body: String) {
        let c = UNMutableNotificationContent()
        c.title = title
        c.body = body
        center.add(UNNotificationRequest(identifier: id, content: c, trigger: nil))
    }

    func remove(key: String) {
        center.removeDeliveredNotifications(withIdentifiers: [key])
    }

    func removeAll() {
        center.removeAllDeliveredNotifications()
    }

    func userNotificationCenter(_ c: UNUserNotificationCenter, willPresent n: UNNotification,
                                withCompletionHandler done: @escaping (UNNotificationPresentationOptions) -> Void) {
        let passive: Bool
        if #available(macOS 12.0, *) { passive = n.request.content.interruptionLevel == .passive } else { passive = false }
        done(passive ? [.list] : [.banner, .list, .sound])
    }

    func userNotificationCenter(_ c: UNUserNotificationCenter, didReceive r: UNNotificationResponse,
                                withCompletionHandler done: @escaping () -> Void) {
        if let key = r.notification.request.content.userInfo["key"] as? String {
            if r.actionIdentifier == UNNotificationDismissActionIdentifier {
                onDismiss?(key)
            } else if r.actionIdentifier == UNNotificationDefaultActionIdentifier {
                onOpen?(key)
            }
        }
        done()
    }
}

/// Launch at login via SMAppService (macOS 13+).
enum LoginItem {
    static var isEnabled: Bool { SMAppService.mainApp.status == .enabled }
    static var needsApproval: Bool { SMAppService.mainApp.status == .requiresApproval }

    @discardableResult
    static func set(_ on: Bool) -> String? {
        do {
            if on { try SMAppService.mainApp.register() } else { try SMAppService.mainApp.unregister() }
            if needsApproval {
                SMAppService.openSystemSettingsLoginItems()
                return "Approve Tether in System Settings → Login Items"
            }
            return nil
        } catch {
            Log.error("login_item.failed", error)
            return "Couldn't change the login item (\(error.localizedDescription))"
        }
    }
}
