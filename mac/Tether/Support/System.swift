/// Watches the general pasteboard (there is no change notification on macOS, so we poll the
/// cheap `changeCount`). Skips password-manager items marked concealed or transient
/// (nspasteboard.org conventions) and our own writes.
final class ClipboardWatcher {
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var ownCount = -1
    var onCopy: ((String) -> Void)?
    /// Every non-concealed text copy (clipboard history), whether or not it is sent.
    var onCopyAny: ((String) -> Void)?
    /// An image copy: bytes and file extension ("png" / "jpg"). 0.5.1: Finder-copied image
    /// files send the picture, not their name.
    var onImage: ((Data, String) -> Void)?

    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            self?.poll()
        }
        t.tolerance = 0.25
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Text from the phone: put it on the pasteboard without echoing it back.
    func set(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        ownCount = pb.changeCount
        lastCount = pb.changeCount
    }

    var currentText: String? { NSPasteboard.general.string(forType: .string) }

    /// The clipboard image as PNG (PNG or TIFF on the pasteboard), nil when there is none.
    var currentImagePNG: Data? {
        let pb = NSPasteboard.general
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    /// What the current pasteboard really is (0.5.1, see PasteboardClassifier).
    enum Content {
        case image(Data, String)
        case text(String)
        case none
    }

    var current: Content {
        let pb = NSPasteboard.general
        let types = (pb.types ?? []).map(\.rawValue)
        let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        let text = pb.string(forType: .string)
        switch PasteboardClassifier.choose(types: types, filePaths: urls.map(\.path), hasText: text?.isEmpty == false) {
        case .imageFile(let path):
            return Self.imageFile(path).map { .image($0.0, $0.1) } ?? .none
        case .imageData:
            return currentImagePNG.map { .image($0, "png") } ?? .none
        case .text:
            return text.map { .text($0) } ?? .none
        case .skip:
            return .none
        }
    }

    /// An image file's bytes: JPEG and PNG as they are, anything else (HEIC, TIFF, GIF…) as PNG
    /// so every Android app can paste it. Nil over 25 MB or unreadable.
    static func imageFile(_ path: String) -> (Data, String)? {
        let url = URL(fileURLWithPath: path)
        let ext = url.pathExtension.lowercased()
        guard let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize, size <= 25 * 1_048_576 else { return nil }
        if ext == "png" || ext == "jpg" || ext == "jpeg" {
            return (try? Data(contentsOf: url)).map { ($0, ext == "png" ? "png" : "jpg") }
        }
        guard let img = NSImage(contentsOf: url), let tiff = img.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return (png, "png")
    }

    /// A photo or scan for Insert from Phone: the picture (or PDF) plus its file URL, so apps
    /// that take images and apps that take files can both paste it. Not echoed to the phone.
    func setFile(_ url: URL) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        if url.pathExtension.lowercased() == "pdf", let pdf = try? Data(contentsOf: url) {
            item.setData(pdf, forType: .pdf)
        } else if let img = NSImage(contentsOf: url), let tiff = img.tiffRepresentation {
            if let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) { item.setData(png, forType: .png) }
            item.setData(tiff, forType: .tiff)
        }
        item.setString(url.absoluteString, forType: .fileURL)
        pb.writeObjects([item])
        ownCount = pb.changeCount
        lastCount = pb.changeCount
    }

    /// An image from the phone: put it on the pasteboard without echoing it back.
    func setImage(_ image: NSImage) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.writeObjects([image])
        ownCount = pb.changeCount
        lastCount = pb.changeCount
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard pb.changeCount != ownCount else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped) else {
            Log.info("clip.skipped_concealed")
            return
        }
        switch current {
        case .text(let s):
            onCopy?(s)
            onCopyAny?(s)
        case .image(let data, let ext):
            Log.info("clip.image_copied", ["ext": ext, "bytes": "\(data.count)"])
            onImage?(data, ext)
        case .none:
            Log.info("clip.not_sent", ["types": (pb.types ?? []).prefix(4).map(\.rawValue).joined(separator: ",")])
        }
    }
}

/// Posts mirrored notifications through UserNotifications. macOS Focus / Do Not Disturb is
/// applied by the system to everything we post; "silent" apps are delivered without sound
/// and as passive (no banner). Notifications whose phone app offers buttons get a matching
/// category: an inline text field for replies, plain buttons for the rest (0.2.0).
final class Notifier: NSObject, UNUserNotificationCenterDelegate {
    static let category = "tether.mirror"
    static let mediaCategory = "tether.media"
    static let revealAction = "tether.reveal"
    static let actionPrefix = "act:"
    static let callCategory = "tether.call"
    static let declineAction = "tether.call.decline"
    static let silenceAction = "tether.call.silence"
    static let answerAction = "tether.call.answer"
    /// Incoming call from a 0.4 phone: Answer as well.
    static let callCategory4 = "tether.call4"
    static let smsCategory = "tether.sms"
    private let center = UNUserNotificationCenter.current()
    private var dynamic: [String: UNNotificationCategory] = [:]
    private let lock = NSLock()
    var onDismiss: ((String) -> Void)?
    var onOpen: ((String) -> Void)?
    /// (notification key, action id, reply text)
    var onAction: ((String, String, String?) -> Void)?
    /// A media notification was clicked (path, reveal-in-Finder?)
    var onMedia: ((String, Bool) -> Void)?
    /// (call id, "decline" / "silence")
    var onCall: ((String, String) -> Void)?
    /// A text-message notification was clicked (thread id).
    var onSms: ((Int64) -> Void)?

    func setUp() {
        center.delegate = self
        registerCategories()
    }

    private func registerCategories() {
        lock.lock()
        var all = Set(dynamic.values)
        lock.unlock()
        all.insert(UNNotificationCategory(identifier: Self.category, actions: [], intentIdentifiers: [], options: [.customDismissAction]))
        all.insert(UNNotificationCategory(
            identifier: Self.mediaCategory,
            actions: [UNNotificationAction(identifier: Self.revealAction, title: "Show in Finder", options: [])],
            intentIdentifiers: [], options: []
        ))
        all.insert(UNNotificationCategory(
            identifier: Self.callCategory,
            actions: [
                UNNotificationAction(identifier: Self.declineAction, title: "Decline", options: [.destructive]),
                UNNotificationAction(identifier: Self.silenceAction, title: "Silence", options: []),
            ],
            intentIdentifiers: [], options: []
        ))
        all.insert(UNNotificationCategory(
            identifier: Self.callCategory4,
            actions: [
                UNNotificationAction(identifier: Self.answerAction, title: "Answer", options: []),
                UNNotificationAction(identifier: Self.declineAction, title: "Decline", options: [.destructive]),
                UNNotificationAction(identifier: Self.silenceAction, title: "Silence", options: []),
            ],
            intentIdentifiers: [], options: []
        ))
        all.insert(UNNotificationCategory(identifier: Self.smsCategory, actions: [], intentIdentifiers: [], options: []))
        center.setNotificationCategories(all)
    }

    /// A category for this set of buttons (shared by every notification with the same buttons).
    private func category(for actions: [NotifActionInfo]) -> String {
        guard !actions.isEmpty else { return Self.category }
        let sig = actions.map { "\($0.id)|\($0.title)|\($0.reply)" }.joined(separator: "\u{1F}")
        var h: UInt64 = 0xcbf29ce484222325
        for b in sig.utf8 { h = (h ^ UInt64(b)) &* 0x100000001b3 }
        let id = "tether.a.\(String(h, radix: 36))"
        lock.lock()
        let known = dynamic[id] != nil
        if !known {
            let buttons: [UNNotificationAction] = actions.map { a in
                if a.reply {
                    return UNTextInputNotificationAction(identifier: Self.actionPrefix + a.id, title: a.title, options: [],
                                                         textInputButtonTitle: "Send", textInputPlaceholder: "Reply")
                }
                return UNNotificationAction(identifier: Self.actionPrefix + a.id, title: a.title, options: [])
            }
            dynamic[id] = UNNotificationCategory(identifier: id, actions: buttons, intentIdentifiers: [], options: [.customDismissAction])
            if dynamic.count > 60 { dynamic.remove(at: dynamic.startIndex) }
        }
        lock.unlock()
        if !known { registerCategories() }
        return id
    }

    func requestAuthorization(_ done: @escaping (Bool) -> Void) {
        center.requestAuthorization(options: [.alert, .sound, .badge]) { granted, error in
            if let error { Log.warn("notify.auth_error", ["reason": "\(error)"]) }
            done(granted)
        }
    }

    func authorizationStatus(_ done: @escaping (UNAuthorizationStatus) -> Void) {
        center.getNotificationSettings { done($0.authorizationStatus) }
    }

    /// Settings › Notifications › Panel only (0.4.1): alerts live in the panel, no Mac banners.
    static var panelOnly: Bool { PanelOnlyAlerts.isOn() }

    func post(key: String, threadId: String, title: String, subtitle: String?, body: String, banner: Bool, sound: Bool,
              actions: [NotifActionInfo] = []) {
        guard !Self.panelOnly else { return }
        let c = UNMutableNotificationContent()
        c.title = title
        if let subtitle { c.subtitle = subtitle }
        c.body = body
        c.threadIdentifier = threadId
        c.categoryIdentifier = category(for: actions)
        c.userInfo = ["key": key]
        if banner && sound { c.sound = .default }
        if #available(macOS 12.0, *) { c.interruptionLevel = banner ? .active : .passive }
        center.add(UNNotificationRequest(identifier: key, content: c, trigger: nil)) { err in
            if let err { Log.warn("notify.post_failed", ["reason": "\(err)"]) }
        }
    }

    func postLocal(id: String, title: String, body: String, sound: Bool = false) {
        guard !Self.panelOnly else { return }
        let c = UNMutableNotificationContent()
        c.title = title
        c.body = body
        if sound { c.sound = .default }
        center.add(UNNotificationRequest(identifier: id, content: c, trigger: nil))
    }

    /// "Screenshot from your phone" with the image as a thumbnail. Clicking opens it.
    func postMedia(id: String, title: String, body: String, file: URL) {
        guard !Self.panelOnly else { return }
        let c = UNMutableNotificationContent()
        c.title = title
        c.body = body
        c.categoryIdentifier = Self.mediaCategory
        c.userInfo = ["path": file.path]
        // The system moves attachment files into its own store, so hand it a copy.
        let tmp = FileManager.default.temporaryDirectory.appendingPathComponent("tether-thumb-\(id).\(file.pathExtension)")
        try? FileManager.default.removeItem(at: tmp)
        if (try? FileManager.default.copyItem(at: file, to: tmp)) != nil,
           let a = try? UNNotificationAttachment(identifier: "thumb", url: tmp, options: nil) {
            c.attachments = [a]
        }
        center.add(UNNotificationRequest(identifier: "media-\(id)", content: c, trigger: nil)) { err in
            if let err { Log.warn("notify.media_failed", ["reason": "\(err)"]) }
        }
    }

    /// Incoming call banner with Decline / Silence (0.3.0), and Answer for a 0.4 phone.
    func postCall(id: String, caller: String, number: String?, canAnswer: Bool = false) {
        guard !Self.panelOnly else { return }
        let c = UNMutableNotificationContent()
        c.title = caller
        c.body = number.map { $0 == caller ? "Incoming call" : "Incoming call · \($0)" } ?? "Incoming call"
        c.categoryIdentifier = canAnswer ? Self.callCategory4 : Self.callCategory
        c.userInfo = ["call": id]
        c.sound = .default
        if #available(macOS 12.0, *) { c.interruptionLevel = .active }
        center.add(UNNotificationRequest(identifier: "call-\(id)", content: c, trigger: nil))
    }

    func postMissedCall(id: String, caller: String, number: String?) {
        guard !Self.panelOnly else { return }
        let c = UNMutableNotificationContent()
        c.title = "Missed call"
        c.body = number.map { $0 == caller ? caller : "\(caller) · \($0)" } ?? caller
        c.threadIdentifier = "missed-calls"
        center.add(UNNotificationRequest(identifier: "missed-\(id)", content: c, trigger: nil))
    }

    func removeCall(id: String) {
        center.removeDeliveredNotifications(withIdentifiers: ["call-\(id)"])
    }

    func postSms(id: String, thread: Int64, title: String, body: String, sound: Bool) {
        guard !Self.panelOnly else { return }
        let c = UNMutableNotificationContent()
        c.title = title
        c.body = body
        c.threadIdentifier = "sms-\(thread)"
        c.categoryIdentifier = Self.smsCategory
        c.userInfo = ["thread": NSNumber(value: thread)]
        if sound { c.sound = .default }
        center.add(UNNotificationRequest(identifier: "sms-\(id)", content: c, trigger: nil))
    }

    func remove(key: String) {
        center.removeDeliveredNotifications(withIdentifiers: [key])
    }

    func removeAll() {
        center.removeAllDeliveredNotifications()
    }

    func userNotificationCenter(_ c: UNUserNotificationCenter, willPresent n: UNNotification,
                                withCompletionHandler done: @escaping (UNNotificationPresentationOptions) -> Void) {
        let passive: Bool
        if #available(macOS 12.0, *) { passive = n.request.content.interruptionLevel == .passive } else { passive = false }
        done(passive ? [.list] : [.banner, .list, .sound])
    }

    func userNotificationCenter(_ c: UNUserNotificationCenter, didReceive r: UNNotificationResponse,
                                withCompletionHandler done: @escaping () -> Void) {
        let info = r.notification.request.content.userInfo
        if let call = info["call"] as? String {
            if r.actionIdentifier == Self.answerAction {
                onCall?(call, CallActions4.answer)
            } else if r.actionIdentifier == Self.declineAction {
                onCall?(call, CallActions.decline)
            } else if r.actionIdentifier == Self.silenceAction {
                onCall?(call, CallActions.silence)
            }
        } else if let thread = (info["thread"] as? NSNumber)?.int64Value {
            if r.actionIdentifier == UNNotificationDefaultActionIdentifier { onSms?(thread) }
        } else if let path = info["path"] as? String {
            if r.actionIdentifier == Self.revealAction {
                onMedia?(path, true)
            } else if r.actionIdentifier == UNNotificationDefaultActionIdentifier {
                onMedia?(path, false)
            }
        } else if let key = info["key"] as? String {
            if r.actionIdentifier == UNNotificationDismissActionIdentifier {
                onDismiss?(key)
            } else if r.actionIdentifier == UNNotificationDefaultActionIdentifier {
                onOpen?(key)
            } else if r.actionIdentifier.hasPrefix(Self.actionPrefix) {
                let id = String(r.actionIdentifier.dropFirst(Self.actionPrefix.count))
                let text = (r as? UNTextInputNotificationResponse)?.userText
                onAction?(key, id, text)
            }
        }
        done()
    }
}

/// Launch at login via SMAppService (macOS 13+).
enum LoginItem {
    static var isEnabled: Bool { SMAppService.mainApp.status == .enabled }
    static var needsApproval: Bool { SMAppService.mainApp.status == .requiresApproval }

    @discardableResult
    static func set(_ on: Bool) -> String? {
        do {
            if on { try SMAppService.mainApp.register() } else { try SMAppService.mainApp.unregister() }
            if needsApproval {
                SMAppService.openSystemSettingsLoginItems()
                return "Approve Tether in System Settings → Login Items"
            }
            return nil
        } catch {
            Log.error("login_item.failed", error)
            return "Couldn't change the login item (\(error.localizedDescription))"
        }
    }
}
